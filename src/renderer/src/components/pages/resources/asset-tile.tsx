import { useReducer, type DragEvent } from "react";
import { useT } from "@renderer/lib/i18n/i18n-provider";
import { Badge, ThumbTile, type IconName } from "@renderer/components/ui";
import { ModelSlide } from "@renderer/components/shared/slide-view/ModelSlide";
import { useDeckStore } from "@renderer/stores/deck.store";
import { failedThumbUrls, resolveThumbUrl } from "@renderer/lib/asset-thumb";
import type { AssetKind } from "@shared/constants";
import type { DeckStatusSummary } from "@shared/types/deck";
import type { MediaAsset } from "@shared/types/media";

const ICON_BY_KIND: Record<AssetKind, IconName> = {
  video: "video",
  image: "image",
  audio: "audio",
  ppt: "ppt",
};

type AssetTileProps = {
  asset: MediaAsset;
  /** This asset's deck, for a `ppt`, from the grid's single `deck:statuses`
   *  round-trip rather than a per-tile `deck:get`. Three states, all of which
   *  the tile shows differently: `undefined` = not asked yet (skeleton),
   *  `null` = asked, no deck yet (the PPT icon), a summary = there is a deck
   *  (its first slide once `ready`). */
  deckStatus?: DeckStatusSummary | null | undefined;
  kind: AssetKind;
  onClick: () => void;
  onDoubleClick: () => void;
  onDragStart: (e: DragEvent<HTMLButtonElement>) => void;
  selected: boolean;
  tabIndex?: number | undefined;
};

/**
 * One library entry. A deck shows its real first slide once converted; an
 * image or a video shows a small cached thumbnail generated by main
 * (`worship://asset/<id>/thumb`); everything else falls back to its icon.
 *
 * A video deliberately does NOT mount a `<video>` element here. It used to,
 * with `preload="metadata"` — which is a full decoding pipeline per visible
 * tile, and a linked folder of a few hundred clips would open a few hundred of
 * them at once. A JPEG costs nothing to draw.
 */
export function AssetTile({
  asset,
  deckStatus,
  kind,
  onClick,
  onDoubleClick,
  onDragStart,
  selected,
  tabIndex,
}: AssetTileProps) {
  const t = useT();
  // A deck being pre-warmed in the background never has its own preview
  // panel open, so this tile is the only place that progress is visible at
  // all — `undefined` (no bar) once it's ready or if it was never touched.
  const deckEntry = useDeckStore((s) => (kind === "ppt" ? s.byAssetId[asset.id] : undefined));
  const missing = asset.missingSince !== null;

  // Remembered by URL rather than as a flag, so a tile falls through its
  // chain one step at a time and can never oscillate between two URLs that
  // both fail — and so the whole thing clears itself the moment the asset's
  // bytes change, because the version in the URL changes with them. The
  // registry is module-level (see `failedThumbUrls`); this only forces the
  // re-render that picks up the next candidate.
  const [, markFailed] = useReducer((count: number) => count + 1, 0);

  const thumbUrl = resolveThumbUrl({
    asset,
    deckThumbUrl: deckStatus?.thumbUrl ?? null,
    failed: failedThumbUrls,
    kind,
  });

  // A deck drawn from its model has no thumbnail image: its first slide is drawn.
  const modelUrl = missing ? null : (deckStatus?.modelUrl ?? null);

  const converting = !missing && deckEntry?.status === "converting";
  const progress = converting
    ? deckEntry.progress.total > 0
      ? deckEntry.progress.done / deckEntry.progress.total
      : null
    : undefined;

  // Only ever true for a deck, and only while something is genuinely going to
  // appear: the status round-trip is still out, a conversion is running, or it
  // just finished and the grid's (debounced) status refetch hasn't handed this
  // tile its thumbnail yet — without that last case the tile drops back to its
  // icon for half a second between converting and ready, which reads as a
  // failure. A deck that is known NOT to be converted shows its icon: a
  // library of 600 of them must not look like 600 things forever loading.
  const loading =
    kind === "ppt" &&
    !missing &&
    // `deckStatus?.thumbUrl`, not the resolved `thumbUrl`: a thumbnail whose
    // URL failed to load (an evicted slide cache) must fall back to the icon,
    // not sit under a skeleton forever.
    (deckStatus === undefined ||
      converting ||
      (deckEntry?.status === "ready" && (deckStatus?.thumbUrl ?? deckStatus?.modelUrl ?? null) === null));

  return (
    <ThumbTile
      draggable
      icon={ICON_BY_KIND[kind]}
      label={asset.name}
      loading={loading}
      media={modelUrl ? <ModelSlide url={modelUrl} /> : undefined}
      onClick={onClick}
      onDoubleClick={onDoubleClick}
      onDragStart={onDragStart}
      onImageError={() => {
        if (thumbUrl === null) return;
        failedThumbUrls.add(thumbUrl);
        markFailed();
      }}
      overlay={
        missing ? (
          <span className="absolute inset-0 flex items-center justify-center">
            <Badge variant="danger">{t("library.missing")}</Badge>
          </span>
        ) : undefined
      }
      progress={progress}
      selected={selected}
      src={missing ? null : thumbUrl}
      tabIndex={tabIndex}
    />
  );
}
